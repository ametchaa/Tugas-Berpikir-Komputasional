# Program Menentukan Luas Umbul Umbul Segitiga
# Menentukan luas umbul umbul memerlukan tinggi dan alas umbul umbul

# KAMUS
# a : alas : float       dalam cm
# t : tinggi : float     dalam cm
# L : luas : float       dalam cm^2

# Algoritma
a = float(input('Masukkan nilai alas '))
t = float(input('Masukkan nilai tinggi '))

L = 1/2 * a * t

print("Maka luas umbul-umbul adalah " + str(L) + " cm\u00b2")

  